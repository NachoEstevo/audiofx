import { compile } from "../../src/core/compile";
import { getEffect } from "../../src/core/registry";
import type { EffectStep } from "../../src/core/types";

/** A step in short form, leaving out params at their default value. */
export function stepToSpec(step: EffectStep): string {
  const effect = getEffect(step.effect);
  const params = Object.entries(step.params ?? {})
    .filter(([k, v]) => effect.params.find((p) => p.id === k)?.default !== v)
    .map(([k, v]) => `${k}=${typeof v === "number" ? Number(v.toFixed(4)) : v}`);
  let spec = step.effect + (params.length ? ":" + params.join(",") : "");
  if (step.from !== undefined || step.to !== undefined) spec += `@${step.from ?? ""}-${step.to ?? ""}`;
  return spec;
}

export function cliCommand(steps: EffectStep[]): string {
  const fade = steps.find((s) => s.fade !== undefined && (s.from !== undefined || s.to !== undefined))?.fade;
  const mix = steps.find((s) => s.mix !== undefined && s.mix < 1)?.mix;
  const flags = [fade !== undefined && fade !== 0.25 ? `--fade ${fade}` : "", mix !== undefined ? `--mix ${mix}` : ""].filter(Boolean);
  return ["sfx apply input.wav output.wav", ...steps.map((s) => `"${stepToSpec(s)}"`), ...flags].join(" ");
}

/** A chain that layers a library sample: its filtergraph needs the file's path, which the browser never has. */
const usesLibrary = (steps: EffectStep[]) => steps.some((s) => Object.values(s.params ?? {}).some((v) => typeof v === "string" && v.startsWith("library:")));

const libraryNote = (steps: EffectStep[]) =>
  [
    "This chain layers a sample from your library, and the studio never sees file paths.",
    "Print the filtergraph with the real path from the CLI:",
    "",
    ["sfx graph", ...steps.map((s) => `"${stepToSpec(s)}"`)].join(" "),
  ].join("\n");

export function filtergraph(steps: EffectStep[]): string {
  return usesLibrary(steps) ? libraryNote(steps) : compile(steps).graph;
}

/** Snippet for Python render scripts (decode_audio(path, start, dur, filtergraph)). */
export function pythonSnippet(steps: EffectStep[]): string {
  if (usesLibrary(steps)) return libraryNote(steps);
  const graph = compile(steps).graph;
  return [
    "# Filtergraph generated by AudioFX: pass it as-is to ffmpeg -af",
    `FX = ${JSON.stringify(graph)}`,
    "",
    "# with an existing render helper:",
    "audio = decode_audio(path, start, duration, FX)",
    "",
    "# or directly:",
    'subprocess.run([FFMPEG, "-y", "-i", "input.wav", "-af", FX, "output.wav"], check=True)',
  ].join("\n");
}

export function chainJson(steps: EffectStep[]): string {
  return JSON.stringify(compile(steps).steps.map((s, i) => ({ ...steps[i], params: s.params })), null, 2);
}
